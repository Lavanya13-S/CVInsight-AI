/**
 * Reusable skill parser that splits pasted text into individual skill chips.
 * Supports commas, semicolons, vertical bars, newlines, tabs, and bullet points.
 */

const SEPARATOR_REGEX = /[,;|\\\n\t\u2022\u25CF\u25CB\u25AA\u25B8]+/;

export function parseSkillsInput(raw: string): string[] {
  if (!raw || !raw.trim()) return [];
  const parts = raw.split(SEPARATOR_REGEX);
  const skills: string[] = [];
  const seen = new Set<string>();
  for (let part of parts) {
    let skill = part.trim();
    skill = skill.replace(/^[•·\-\s]+|[\s]+$/g, '').trim();
    skill = skill.replace(/^[\(\)\[\]{}]+|[\(\)\[\]{}]+$/g, '').trim();
    if (!skill) continue;
    const lower = skill.toLowerCase();
    if (seen.has(lower)) continue;
    seen.add(lower);
    skills.push(skill);
  }
  return skills;
}

export function parseSkillsInputMerge(
  raw: string,
  existing: string[]
): string[] {
  const newSkills = parseSkillsInput(raw);
  const seen = new Set(existing.map((s) => s.toLowerCase()));
  const result = [...existing];
  for (const s of newSkills) {
    if (!seen.has(s.toLowerCase())) {
      result.push(s);
      seen.add(s.toLowerCase());
    }
  }
  return result;
}

