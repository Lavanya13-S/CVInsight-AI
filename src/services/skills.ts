export function normalizeSkill(skill: string): string {
  const lower = skill.trim().toLowerCase();
  return ALIAS_MAP[lower] ?? lower;
}

export function skillsMatch(candidateSkill: string, requiredSkill: string): boolean {
  return normalizeSkill(candidateSkill) === normalizeSkill(requiredSkill);
}

export function getMatchedSkills(candidateSkills: string[], requiredSkills: string[]): string[] {
  return requiredSkills.filter((r) =>
    candidateSkills.some((c) => skillsMatch(c, r))
  );
}

export function getMissingSkills(candidateSkills: string[], requiredSkills: string[]): string[] {
  return requiredSkills.filter(
    (r) => !candidateSkills.some((c) => skillsMatch(c, r))
  );
}
